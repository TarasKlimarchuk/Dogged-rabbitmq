import { Body, Controller, HttpCode, HttpStatus, Post } from '@nestjs/common';
import {
  ApiAcceptedResponse,
  ApiBadRequestResponse,
  ApiOperation,
  ApiServiceUnavailableResponse,
  ApiTags,
} from '@nestjs/swagger';
import { OrdersService } from './orders.service.js';
import { CreateOrderDto } from '@app/contracts/orders/create-order.dto.js';
import { OrderResponseDto } from './order-response.dto.js';

@ApiTags('orders')
@Controller('orders')
export class OrdersController {
  constructor(private readonly ordersService: OrdersService) {}

  @Post()
  @ApiOperation({
    summary:
      'Place an order. Forwards to broker through retry + circuit breaker; ' +
      'the idempotencyKey must be generated by the original caller so retries never create duplicates.',
  })
  @HttpCode(HttpStatus.ACCEPTED)
  @ApiAcceptedResponse({ type: OrderResponseDto })
  @ApiBadRequestResponse({ description: 'Request body failed validation' })
  @ApiServiceUnavailableResponse({
    description: 'Order broker unavailable; safe to retry with the same idempotencyKey',
  })
  async placeOrder(@Body() order: CreateOrderDto) {
    return this.ordersService.placeOrder(order);
  }
}
